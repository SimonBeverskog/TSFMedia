import {build} from 'esbuild';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {loadPublishedContent} from '../src/sanity.js';

const content = await loadPublishedContent({useCdn: false});
await writeFile(new URL('../dist/cms-snapshot.js', import.meta.url), `// Published Sanity content. Generated by npm run build.\nexport default ${JSON.stringify(content, null, 2)};\n`);
await build({
  entryPoints: [fileURLToPath(new URL('../src/sanity.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../dist/sanity.js', import.meta.url)),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
});
console.log(`Byggt: ${content.events.length} album, ${Object.keys(content.photos).length} bilder, ${content.news.length} nyheter från Sanity.`);
